class JobPortal {
  final String id;
  final String title;
  final String? banglaTitle;
  final String category;
  final String url;
  final String? description;
  final String? badgeText;
  final String? icon;
  final String actionText;
  final bool isFeatured;
  final bool isVerified;
  final int order;

  JobPortal({
    required this.id,
    required this.title,
    this.banglaTitle,
    required this.category,
    required this.url,
    this.description,
    this.badgeText,
    this.icon,
    this.actionText = 'Apply Now',
    this.isFeatured = false,
    this.isVerified = true,
    this.order = 1,
  });

  factory JobPortal.fromJson(Map<String, dynamic> json) {
    return JobPortal(
      id: json['id']?.toString() ?? '',
      title: json['title'] ?? '',
      banglaTitle: json['bangla_title'],
      category: json['category'] ?? 'govt',
      url: json['url'] ?? '',
      description: json['description'],
      badgeText: json['badge_text'],
      icon: json['icon'],
      actionText: json['action_text'] ?? 'Apply Now',
      isFeatured: json['is_featured'] == true || json['is_featured'] == 1,
      isVerified: json['is_verified'] == true || json['is_verified'] == 1,
      order: json['order'] is int ? json['order'] : int.tryParse(json['order']?.toString() ?? '1') ?? 1,
    );
  }

  Map<String, dynamic> toJson() {
    return {
      'id': id,
      'title': title,
      'bangla_title': banglaTitle,
      'category': category,
      'url': url,
      'description': description,
      'badge_text': badgeText,
      'icon': icon,
      'action_text': actionText,
      'is_featured': isFeatured,
      'is_verified': isVerified,
      'order': order,
    };
  }
}

